// Writes the files that let people install Raman into their AI tool, from the one source of the method
// (src/lib/prism/guide.ts): the Agent Skill and the Claude Code marketplace entry.
//   npm run build:skill                      no host yet: the skill reads the host from RAMAN_URL
//   npm run build:skill -- https://host      also names the host and bundles the MCP server in the plugin
// Formats (verified 2026-11-10):
//   SKILL.md: name = parent directory, 1-64 chars; description 1-1024 chars  https://agentskills.io/specification.md
//   plugin.json: name is the only required field; skills/<name>/SKILL.md sits at the plugin root
//   https://code.claude.com/docs/en/plugins/manifest-reference.md
//   marketplace.json: name, owner, plugins[{name, source}]; "./" = this repo, as in
//   https://github.com/anthropics/skills/blob/main/.claude-plugin/marketplace.json
//   https://code.claude.com/docs/en/plugins/create-marketplace.md
import { mkdirSync, writeFileSync } from "node:fs";
import { GUIDE } from "../src/lib/prism/guide";

const NAME = "agent-raman";
const host = (process.argv[2] ?? "").replace(/\/+$/, "");
if (host && !/^https:\/\/[a-z0-9.-]+(:\d+)?$/i.test(host)) {
  console.error("Pass the host as https://name (no path), or nothing.");
  process.exit(1);
}
const base = host || "$RAMAN_URL";

const description =
  "Plan a task before an AI agent starts it. Splits the request into needs, binds each need to a real MCP server, " +
  "skill, plugin or model from the AgentRamaN catalog, and returns one task.md with inputs, constraints, checks " +
  "and a list of what could not be resolved. Use when the user asks to plan, scope or prepare a task for Claude " +
  "Code, Codex, ChatGPT or Cursor, asks which tools, MCP servers or skills a task needs, or says \"use AgentRamaN\". " +
  "Plans only: it never runs the task.";
if (description.length > 1024) throw new Error("description is over 1024 characters");

const skill = `---
name: ${NAME}
description: ${JSON.stringify(description)}
compatibility: Needs the agent-raman MCP server, or network access to an AgentRamaN host.
---

<!-- Generated by scripts/build-skill.ts from src/lib/prism/guide.ts. Edit the source, not this file. -->

## Reach AgentRamaN first

1. If the tools \`raman_guide\`, \`raman_find\`, \`raman_get\`, \`raman_check\` and \`raman_render\` are available
   (MCP server "${NAME}"), use them.
2. Otherwise call the same tools over HTTP at \`${base}/api/v1/\`: \`GET guide\`, and \`POST find\`, \`get\`,
   \`check\`, \`render\` with the same JSON input.${host ? "" : " `RAMAN_URL` is the address of the AgentRamaN host; ask the user for it when it is not set."}
3. If neither works, stop and tell the user to connect the server, for example
   \`claude mcp add --transport http ${NAME} ${base}/api/mcp\`. Do not plan from memory: without the
   catalog no tool can be verified, and an unverified tool name must never be presented as a pick.

No model key is needed. AgentRamaN's server looks up the catalog, enforces the rules and renders the file; you do
the thinking. Send no secrets: refer to credentials by env var name.

${GUIDE.trim()}
`;

const blurb = "Plan a task before an agent starts it: needs, real tools from the AgentRamaN catalog, one task.md.";

// The repo root is the plugin: skills/ is found by convention, the manifest names the MCP server once a host
// exists. `claude plugin eval` needs the manifest (https://code.claude.com/docs/en/plugin-evals.md, 2026-11-10).
const plugin: Record<string, unknown> = {
  name: NAME,
  description: blurb,
  version: "0.1.0",
  author: { name: "mhkr9100" },
  repository: "https://github.com/mhkr9100/Agent-Raman",
};
if (host) plugin.mcpServers = { [NAME]: { type: "http", url: `${host}/api/mcp` } };

const marketplace = {
  name: NAME,
  owner: { name: "mhkr9100" },
  metadata: { description: "AgentRamaN: know what your agent needs before it starts.", version: "0.1.0" },
  plugins: [{ name: NAME, description: blurb, source: "./" }],
};

mkdirSync(`skills/${NAME}`, { recursive: true });
mkdirSync(".claude-plugin", { recursive: true });
writeFileSync(`skills/${NAME}/SKILL.md`, skill);
writeFileSync(".claude-plugin/plugin.json", JSON.stringify(plugin, null, 2) + "\n");
writeFileSync(".claude-plugin/marketplace.json", JSON.stringify(marketplace, null, 2) + "\n");
console.log(`skills/${NAME}/SKILL.md  ${skill.split("\n").length} lines, description ${description.length} chars`);
console.log(`.claude-plugin/plugin.json + marketplace.json  ${host ? `MCP server at ${host}/api/mcp` : "no MCP server bundled (no host given)"}`);
